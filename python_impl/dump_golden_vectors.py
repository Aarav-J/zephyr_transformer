"""Generate golden test vectors for the C port.

Reuses the already-validated NumPy attention implementation to produce a C
header with fixed input/weight/expected-output arrays. The C code consumes
these directly instead of inventing its own random data, so a mismatch can
only mean a C translation bug -- not a different RNG draw.
"""
import numpy as np

import attention

SEED = 42
SEQ_LEN, D_MODEL, D_K = 4, 8, 8


def generate():
    np.random.seed(SEED)
    x = np.random.randn(SEQ_LEN, D_MODEL)
    w_q, w_k, w_v = (np.random.randn(D_MODEL, D_K) for _ in range(3))
    b_q, b_k, b_v = (np.random.randn(D_K) for _ in range(3))

    q = attention.linear(x, w_q, b_q)
    k = attention.linear(x, w_k, b_k)
    v = attention.linear(x, w_v, b_v)
    out = attention.scaled_dot_product_attention(q, k, v)

    return {
        "X": x, "W_Q": w_q, "W_K": w_k, "W_V": w_v,
        "B_Q": b_q, "B_K": b_k, "B_V": b_v,
        "EXPECTED_Q": q, "EXPECTED_K": k, "EXPECTED_V": v,
        "EXPECTED_OUTPUT": out,
    }


def c_array_literal(name, arr):
    """Render a 1D or 2D float array as a C initializer."""
    if arr.ndim == 1:
        dims = f"[{arr.shape[0]}]"
        body = ", ".join(f"{v:.8f}f" for v in arr)
        return f"static const float {name}{dims} = {{{body}}};"

    dims = f"[{arr.shape[0]}][{arr.shape[1]}]"
    rows = []
    for row in arr:
        rows.append("    {" + ", ".join(f"{v:.8f}f" for v in row) + "}")
    body = ",\n".join(rows)
    return f"static const float {name}{dims} = {{\n{body}\n}};"


def write_header(path, vectors):
    lines = [
        "/* Auto-generated by python_impl/dump_golden_vectors.py. Do not edit. */",
        "#ifndef GOLDEN_VECTORS_H",
        "#define GOLDEN_VECTORS_H",
        "",
        f"#define SEQ_LEN {SEQ_LEN}",
        f"#define D_MODEL {D_MODEL}",
        f"#define D_K {D_K}",
        "",
    ]
    for name, arr in vectors.items():
        lines.append(c_array_literal(name, arr))
        lines.append("")
    lines.append("#endif /* GOLDEN_VECTORS_H */")
    lines.append("")

    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    vectors = generate()
    write_header("../c_impl/golden_vectors.h", vectors)
